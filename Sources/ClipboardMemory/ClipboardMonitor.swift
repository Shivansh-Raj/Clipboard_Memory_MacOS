import AppKit
import ClipboardCore

/// Polls NSPasteboard.changeCount (macOS offers no change notification) and records new clips.
/// The poll itself is a single integer comparison; content is only read after a change.
final class ClipboardMonitor {
    private let store: HistoryStore
    private let writer: PasteboardWriter
    private let settings = AppSettings.shared
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private let workQueue = DispatchQueue(label: "clipboard.ingest", qos: .utility)

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
    ]
    private static let maxTextBytes = 4_000_000

    init(store: HistoryStore, writer: PasteboardWriter) {
        self.store = store
        self.writer = writer
    }

    func start() {
        stop()
        lastChangeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.2
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() { timer?.invalidate(); timer = nil }

    private func poll() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if count == writer.ignoredChangeCount { return }   // our own write
        if settings.paused { return }
        capture(pb)
    }

    private func capture(_ pb: NSPasteboard) {
        let types = Set((pb.types ?? []).map(\.rawValue))
        if !types.isDisjoint(with: Self.ignoredTypes) { return }

        let front = NSWorkspace.shared.frontmostApplication
        let bundle = front?.bundleIdentifier
        if let bundle, settings.excludedApps.contains(bundle) { return }
        let appName = front?.localizedName

        // Finder file copies.
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            save(NewClip(kind: .file, text: paths, sourceApp: appName, sourceBundleID: bundle))
            return
        }

        if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard text.utf8.count <= Self.maxTextBytes else { return }
            let rtf = pb.data(forType: .rtf)
            let html = pb.data(forType: .html)
            let protect = settings.protectSensitive && settings.sensitiveAction == .skip
            workQueue.async { [weak self] in
                guard let self else { return }
                if protect, SensitiveDetector.detect(text) != nil { return }
                var kind = ContentClassifier.classify(text)
                if kind == .text && (rtf != nil || html != nil) { kind = .richText }
                let hasRich = rtf.map { $0.count < 5_000_000 } ?? true
                self.save(NewClip(kind: kind, text: text, rtf: hasRich ? rtf : nil,
                                  html: (html?.count ?? 0) < 5_000_000 ? html : nil,
                                  sourceApp: appName, sourceBundleID: bundle), onQueue: true)
            }
            return
        }

        // Images.
        let png = pb.data(forType: .png)
        let tiff = png == nil ? pb.data(forType: .tiff) : nil
        guard png != nil || tiff != nil else { return }
        let limit = settings.maxImageMB * 1_048_576
        let indexText = settings.indexImageText
        workQueue.async { [weak self] in
            guard let self else { return }
            var data = png
            var size = CGSize.zero
            if data == nil, let tiff, let rep = NSBitmapImageRep(data: tiff) {
                data = rep.representation(using: .png, properties: [:])
                size = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
            } else if let png, let rep = NSBitmapImageRep(data: png) {
                size = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
            }
            guard let data, data.count <= limit, size.width > 0 else { return }
            let clip = NewClip(kind: .image, imagePNG: data, imageWidth: Int(size.width), imageHeight: Int(size.height),
                               sourceApp: appName, sourceBundleID: bundle)
            if let r = self.save(clip, onQueue: true), r.isNew, indexText,
               let entry = self.store.payload(id: r.id)?.imageURL {
                OCR.recognize(imageAt: entry) { [store = self.store] text in
                    if !text.isEmpty { store.setOCR(r.id, text); NotificationCenter.default.post(name: .historyChanged, object: nil) }
                }
            }
        }
    }

    @discardableResult
    private func save(_ clip: NewClip, onQueue: Bool = false) -> (id: Int64, isNew: Bool)? {
        let result = try? store.save(clip)
        DispatchQueue.main.async { NotificationCenter.default.post(name: .historyChanged, object: nil) }
        return result
    }
}
